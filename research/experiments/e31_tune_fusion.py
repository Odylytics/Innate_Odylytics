"""E31: tune the fusion weights and threshold A on the E29 results, tuning on 3 folds, TESTING on the other 2 folds (entirely different people).

Input: pickle exported by e29 (E29_DUMP): each row (person, known-recipient risk, new-recipient risk, human, owner, fold). Risk is recomputed as wb·(1−human) + wo·(1−owner) (+ wn for a new recipient).
Objective: among configurations where the sitting owner is still allowed >= the current level (77% on the tune folds), pick the one that maximizes the mean NOT-allow rate of the "adaptive attacker" groups
(PIN-knowing impostor, T4, template-aware bot 1.0 and 0.5, replay ±15/20/30%). B kept at 0.55, HUMAN_HOLD 0.3, amount 0.
Run: python research/experiments/e31_tune_fusion.py <path to pickle>
"""
import pickle, sys
from pathlib import Path
import numpy as np

ROOT = Path(__file__).parents[2]
R = pickle.load(open(sys.argv[1], "rb"))
G = list(R)
OWN, ADV = G[0], [G[2], G[6], G[11], G[12], G[8], G[9], G[10]]
TUNE, TEST = {0, 1, 2}, {3, 4}
B, HH = 0.55, 0.3


def arr(g, folds):
    rows = [r for r in R[g] if r[5] in folds]
    return np.array([r[3] for r in rows]), np.array([r[4] if r[4] is not None else 0.5 for r in rows])


def allow_rate(g, folds, wb, wo, A, new=False):
    h, o = arr(g, folds)
    risk = wb * (1 - h) + wo * (1 - o) + (0.15 if new else 0)
    hold = (h < HH) | (risk > B)
    return float(((~hold) & (risk < A)).mean())


def adv_block(folds, wb, wo, A):
    return float(np.mean([1 - allow_rate(g, folds, wb, wo, A) for g in ADV]))


cur = (0.40, 0.35, 0.25)
base_own = allow_rate(OWN, TUNE, *cur)
best = None
for wo in np.arange(0.20, 0.71, 0.05):
    for wb in np.arange(0.20, 0.51, 0.05):
        for A in np.arange(0.05, 0.50, 0.01):
            if allow_rate(OWN, TUNE, wb, wo, A) < base_own:
                continue
            s = adv_block(TUNE, wb, wo, A)
            if best is None or s > best[0]:
                best = (s, wb, wo, A)
_, wb, wo, A = best
L = ["# E31 — tuning the fusion weights and threshold A (tune on 3 folds, test on 2 folds of E29)", "",
     f"Constraint: sitting owner allow on the tune folds >= current ({100 * base_own:.0f}%). Objective: mean not-allow rate of the 7 adaptive attack groups. "
     "Grid: wo 0.20–0.70, wb 0.20–0.50, A 0.05–0.49; B=0.55; amount = 0; new-recipient weight 0.15. Naive bots and replay ≤±10% are already at 100% in every configuration, so they are not in the objective.", "",
     f"Selected: wb={wb:.2f}, wo={wo:.2f}, A={A:.2f} (current: wb=0.40, wo=0.35, A=0.25).", "",
     "| Group | current (test) | tuned (test) | current (tune) | tuned (tune) |", "|---|---|---|---|---|"]
for g in [OWN] + ADV:
    L.append(f"| {g}{' (allow)' if g == OWN else ' (not allow)'} | "
             + " | ".join(f"{100 * (allow_rate(g, f, *p) if g == OWN else 1 - allow_rate(g, f, *p)):.0f}%" for f, p in
                          ((TEST, cur), (TEST, (wb, wo, A)), (TUNE, cur), (TUNE, (wb, wo, A)))) + " |")
L.append(f"| **mean of attack groups** | {100 * adv_block(TEST, *cur):.0f}% | {100 * adv_block(TEST, wb, wo, A):.0f}% | {100 * adv_block(TUNE, *cur):.0f}% | {100 * adv_block(TUNE, wb, wo, A):.0f}% |")
L += ["", f"Walking owner allow (test): current {100 * allow_rate(G[1], TEST, *cur):.0f}%, tuned {100 * allow_rate(G[1], TEST, wb, wo, A):.0f}%. "
      f"NEW recipient, sitting owner allow (test): current {100 * allow_rate(OWN, TEST, *cur, new=True):.0f}%, tuned {100 * allow_rate(OWN, TEST, wb, wo, A, new=True):.0f}%.", "",
      "Limitations: a single tune/test split, 97 people; the objective is the team's choice (7 groups weighted equally); bots are generated by the team; no team data yet. Do not apply if the improvement on the test folds is smaller than the variation between the two folds."]
Path(ROOT / "research/results/e31_tune_fusion.md").write_text("\n".join(L) + "\n", encoding="utf-8")
print("\n".join(L))
