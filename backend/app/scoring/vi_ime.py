"""Vietnamese typing style (Telex/VNI) from the `challenge` field, with NO need for the content the user typed.

The challenge phrase is generated by the server, so the server knows the correct phrase. From it we can compute how many "transform" keys each syllable needs (circumflex/horn/đ marks and tone marks).
Transform keys add NO character (n=0 in InputEvent), so they reveal: (1) Telex or VNI (letter keys or number keys), (2) whether the tone mark is typed right after the vowel or at the end of the syllable,
(3) the correction rate, (4) whether a Vietnamese input method is used at all (an accented phrase with no transform key = set/pasted/keyboard without an input method).
Habits 2 and 1 do not depend on the specific phrase, so they address exactly the weakness of E13 (challenge phrase differs from the enrollment phrase).

UNMEASURED HYPOTHESIS: there is no real Vietnamese typing data yet. This module only extracts features; it is not wired into fusion/owner.
"""

import unicodedata

_TONE_TELEX = {"̀": "f", "́": "s", "̉": "r", "̃": "x", "̣": "j"}
_TONE_VNI = {"̀": "2", "́": "1", "̉": "3", "̃": "4", "̣": "5"}
# diacritic -> (second Telex key, VNI key)
_MARK = {"̂": {"a": ("a", "6"), "e": ("e", "6"), "o": ("o", "6")}, "̆": {"a": ("w", "8")}, "̛": {"o": ("w", "7"), "u": ("w", "7")}}
COMPOSE_MS = 20  # Unikey "backspace then reinsert" style: delete + key within <= 20 ms = one transform key


def syllable_units(word: str) -> list[dict]:
    """Split a syllable into units: base, mark (transform key for circumflex/horn/đ, per telex/vni), tone (tone-mark key)."""
    units = []
    for ch in unicodedata.normalize("NFD", word.lower()):
        if ch == "đ":
            units.append({"base": "d", "mark": ("d", "9"), "tone": None})
        elif unicodedata.combining(ch):
            u = units[-1]
            if ch in _TONE_TELEX:
                u["tone"] = (_TONE_TELEX[ch], _TONE_VNI[ch])
            else:
                u["mark"] = _MARK[ch][u["base"]]
        else:
            units.append({"base": ch, "mark": None, "tone": None})
    return units


def tone_choices(word: str) -> int:
    """Number of valid places to type the tone-mark key (right after the marked vowel, or after each remaining letter up to the end of the syllable). 1 = no choice; 0 = no tone mark."""
    u = syllable_units(word)
    idx = next((i for i, x in enumerate(u) if x["tone"]), None)
    return 0 if idx is None else len(u) - idx


def expected_transforms(phrase: str) -> int:
    """Minimum number of transform keys to type the phrase in Telex/VNI (one key per circumflex/horn/đ, one per tone mark)."""
    return sum((u["mark"] is not None) + (u["tone"] is not None) for w in phrase.split() for u in syllable_units(w))


def _norm(events: list[dict]) -> list[tuple[int, str, str | None]]:
    """-> [(t, 'char'|'transform'|'delete'|'other', cls)]; merge a delete+key in close succession into 'transform'."""
    out, i = [], 0
    while i < len(events):
        e = events[i]
        nxt = events[i + 1] if i + 1 < len(events) else None
        if e["kind"] == "delete" and nxt and nxt["kind"] == "key" and nxt["n"] == 1 and nxt["t"] - e["t"] <= COMPOSE_MS:
            out.append((nxt["t"], "transform", nxt.get("cls")))
            i += 2
            continue
        if e["kind"] == "key":
            out.append((e["t"], "transform" if e["n"] == 0 else "char", e.get("cls")))
        elif e["kind"] == "delete":
            out.append((e["t"], "delete", None))
        else:
            out.append((e["t"], "other", None))
        i += 1
    return out


def style_features(events: list[dict], phrase: str) -> dict[str, float]:
    """Typing-style features. events = fields[name=challenge].events (dict), phrase = the phrase the server generated. Missing data -> the key is dropped."""
    f: dict[str, float] = {}
    ev = _norm(events)
    chars = [e for e in ev if e[1] == "char"]
    trans = [e for e in ev if e[1] == "transform"]
    need = expected_transforms(phrase)
    if need >= 3 and len(chars) >= 5:  # accented phrase typed with no transform key: no Vietnamese input method used (soft signal)
        f["vi_ime_coverage"] = min(1.0, len(trans) / need)
    if not trans:
        return f
    known = [e for e in trans if e[2] is not None]  # a web page on a phone sees no key: cls = None, do not guess Telex/VNI
    if known:
        f["vi_vni_frac"] = sum(e[2] == "digit" for e in known) / len(known)
    f["vi_delete_rate"] = sum(e[1] == "delete" for e in ev) / max(1, len(chars))
    gc = [b[0] - a[0] for a, b in zip(ev, ev[1:]) if b[1] == "char"]
    gt = [b[0] - a[0] for a, b in zip(ev, ev[1:]) if b[1] == "transform"]
    if len(gc) >= 3 and len(gt) >= 2:
        f["vi_transform_gap_ratio"] = (sum(gt) / len(gt)) / max(1.0, sum(gc) / len(gc))

    # lateness of the tone-mark key: 0 = right after the vowel, 1 = end of the syllable; only syllables with >= 2 places to put it count
    words, cur = [], []
    for e in ev:
        if e[1] == "other" or (e[1] == "char" and e[2] == "space"):
            words.append(cur)
            cur = []
        else:
            cur.append(e)
    words.append(cur)
    late = []
    for w, syl in zip([w for w in words if w], phrase.split()):
        k = tone_choices(syl) - 1
        if k < 1:
            continue
        ti = max((i for i, e in enumerate(w) if e[1] == "transform"), default=None)
        if ti is None:
            continue
        after = min(k, sum(e[1] == "char" for e in w[ti + 1 :]))
        late.append((k - after) / k)
    if late:
        f["vi_tone_late"] = sum(late) / len(late)
    return f
